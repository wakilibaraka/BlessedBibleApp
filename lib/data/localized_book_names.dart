/// The name to show for [canonicalName] in [languageCode]. Falls back to
/// [canonicalName] for languages without a table and for non-book names.
String localizedBookName(String canonicalName, String languageCode) {
  final names = kLocalizedBookNames[languageCode];
  if (names == null) return canonicalName;
  final index = kBibleBookNames.indexOf(canonicalName);
  if (index < 0 || index >= names.length) return canonicalName;
  return names[index];
}

extension LocalizedBookName on BuildContext {
  /// [canonicalName] in the interface language: "Mwanzo" for Genesis when the
  /// app is in Kiswahili, "Genesis" in English.
  String bookNameInLocale(String canonicalName) => localizedBookName(
      canonicalName, Localizations.localeOf(this).languageCode);

  /// [reference] ("Daniel 11:27") with its leading book name in the interface
  /// language. Non-reference text is returned unchanged.
  String referenceInLocale(String reference) =>
      localizedReference(reference, Localizations.localeOf(this).languageCode);
}

/// Rewrites the leading canonical book name of a reference ("1 Samuel 3:4",
/// "Genesis 1") into [languageCode]. Text that does not start with a book name
/// is returned unchanged, so it is safe on mixed strings.
String localizedReference(String reference, String languageCode) {
  final names = kLocalizedBookNames[languageCode];
  if (names == null) return reference;
  final start = reference.length - reference.trimLeft().length;
  final rest = reference.substring(start);
  for (var i = 0; i < kBibleBookNames.length; i++) {
    final english = kBibleBookNames[i];
    if (!rest.startsWith(english)) continue;
    if (rest.length == english.length) {
      return reference.substring(0, start) + names[i];
    }
    final next = rest[english.length];
    if (next != ' ' && next != ':') continue;
    return reference.substring(0, start) +
        names[i] +
        rest.substring(english.length);
  }
  return reference;
}
